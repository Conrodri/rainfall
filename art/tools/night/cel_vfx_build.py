"""Original procedural VFX builders; cel only on smoke and meteor's opaque disc.
System Python driver; Blender --background --python this_file -- --render [--resume].
No source blend saves, resources, normals, light-only effects or emission masks changed.
"""
import sys, json, hashlib, subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).parent
sys.path[:0] = [str(ROOT/'art/tools/cel'), str(ROOT/'art/tools/vfx'), str(ROOT/'art/tools/iso')]
import cel_style as cel
WORK = ROOT/'art/blender/cel/vfx'
TARGETS = {'meteor': 'prop', 'meteor_impact': 'vfx', 'monster_death': 'vfx'}
REPORT = HERE/'_cel_vfx_verification.json'

def digest(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()

def shade(L, prof):
    import bpy
    for obj in L.G['objs']:
        kind = obj['k']
        if kind not in ('smoke', 'disc'):
            continue
        # The original alpha/noise/phase graph survives intact. Only its colour
        # socket receives the ramp generated by the shared cel module.
        original = obj.data.materials[0]
        mat = original.copy()
        obj.data = obj.data.copy()
        obj.data.materials.clear(); obj.data.materials.append(mat)
        template = bpy.data.materials.new('CEL palette'); template.use_nodes = True
        template.node_tree.nodes.get('Principled BSDF').inputs['Base Color'].default_value = obj.color
        cel.toon_materials(prof)
        ramp_src = next(n for n in template.node_tree.nodes if n.type == 'VALTORGB')
        ns, ls = mat.node_tree.nodes, mat.node_tree.links
        em = next(n for n in ns if n.type == 'EMISSION')
        old_color = em.inputs[0].links[0].from_socket
        ramp = ns.new('ShaderNodeValToRGB'); ramp.name = 'CEL shared tones'
        ramp.color_ramp.interpolation = ramp_src.color_ramp.interpolation
        src = ramp_src.color_ramp.elements
        for i, el in enumerate(src):
            dest = ramp.color_ramp.elements[i] if i < 2 else ramp.color_ramp.elements.new(el.position)
            dest.position = el.position; dest.color = el.color
        if kind == 'smoke':
            # Last procedural colour mix supplies the broad smoke lobes;
            # continuous opacity and object tint remain the originals.
            factor = old_color.node.inputs[0].links[0].from_socket
        else:
            # Original radial disc coordinate; no added geometry or animation.
            oi = next(n for n in ns if n.type == 'OBJECT_INFO')
            factor = None
            for n in ns:
                if n.type == 'MATH' and n.operation == 'MULTIPLY' and n.inputs[1].default_value == 2.0:
                    if n.inputs[0].is_linked and n.inputs[0].links[0].from_node.type == 'MATH' and n.inputs[0].links[0].from_node.operation == 'POWER':
                        inv = ns.new('ShaderNodeMath'); inv.operation = 'SUBTRACT'; inv.inputs[0].default_value = 1
                        ls.new(n.outputs[0], inv.inputs[1]); factor = inv.outputs[0]; break
            assert factor is not None
        ls.new(factor, ramp.inputs[0])
        color = ramp.outputs[0]
        if kind == 'disc':
            edge = ns.new('ShaderNodeMath'); edge.operation = 'GREATER_THAN'
            ls.new(factor, edge.inputs[0])
            edge.inputs[1].default_value = 2*cel.profile(prof)['ink_px']/(obj.scale.x*50)
            ink = ns.new('ShaderNodeMixRGB')
            ink.inputs[1].default_value = (*cel.INK_RGB, 1)
            ls.new(edge.outputs[0], ink.inputs[0]); ls.new(color, ink.inputs[2])
            color = ink.outputs[0]
        ls.new(color, em.inputs[0])
        bpy.data.materials.remove(template)

def render():
    import bpy, vfx_lib as L, fx_all as fx
    L.ROOT = WORK
    for name, prof in TARGETS.items():
        E = fx.EFFECTS[name]; w, h = E['size']
        L.setup(w, h, tz=E.get('tz', 0), ty=E.get('ty', 0), ppu=E.get('ppu', 64), samples=8)
        cel.install(prof, normals=False)
        # vfx_lib renders shader billboards directly, without configure_passes.
        # Keep its transparency graph; apply shared generated palettes above.
        for anim, A in E['anims'].items():
            for f in range(A['n']):
                dest = WORK/'art/renders/vfx'/name/anim/('x_%02d.png' % f)
                if '--resume' in sys.argv and dest.exists(): continue
                L.clear(); A['build'](f, A['n'])
                L.set_phase(6.283185307*f/A['n'])
                shade(L, prof)
                L.render(name, anim, f, 6.283185307*f/A['n'])
        cel.uninstall()
    print('PASS CEL VFX render', flush=True)

def driver():
    from PIL import Image
    import numpy as np
    sprites = ROOT/'game/assets/sprites/vfx'
    before = {str(p.relative_to(sprites)): digest(p) for p in sprites.rglob('*') if p.is_file()}
    for name in TARGETS: cel.archive_folder('vfx/'+name)
    bytes_before = sum(p.stat().st_size for p in sprites.rglob('*.png') if p.parent.name not in TARGETS)
    bytes_before += sum(p.stat().st_size for name in TARGETS for p in (cel.ARCHIVE/'vfx'/name).glob('*.png'))
    WORK.mkdir(parents=True, exist_ok=True)
    args = [cel.BLENDER, '--background', '--python', str(Path(__file__).resolve()), '--', '--render']
    if '--resume' in sys.argv: args.append('--resume')
    with (HERE/'_cel_vfx_blender.log').open('w') as log:
        result = subprocess.run(args, stdout=log, stderr=subprocess.STDOUT)
    assert result.returncode == 0, 'Blender: art/tools/night/_cel_vfx_blender.log'
    # Reuse the original packer in an isolated output root. Its .tres and its
    # full-size emission products stay outside game; original _e is unchanged.
    import pack_vfx, fx_all as fx
    pack_vfx.ROOT = WORK
    checks = []; samples = []; rewritten = set()
    for name in TARGETS:
        pack_vfx.pack(name)
        E = fx.EFFECTS[name]; w, h = E['size']
        row = []
        for anim, A in E['anims'].items():
            rel = f'vfx/{name}/{anim}.png'
            dest = cel.GAME_SPRITES/rel
            source = WORK/'game/assets/sprites/vfx'/name/(anim+'.png')
            assert Image.open(source).size == Image.open(dest).size
            dest.write_bytes(source.read_bytes()); rewritten.add(str(dest.relative_to(sprites)))
            # VFX fade-out cells are deliberately translucent: check_sheet's
            # creature threshold alpha>240 is invalid for these original frames.
            result = cel.check_sheet(rel, normals=False)
            pixels = np.asarray(Image.open(dest).convert('RGBA'))
            reference = np.asarray(Image.open(cel.ARCHIVE/rel).convert('RGBA'))
            hashes = []; translucent = []
            assert pixels.shape[:2] == (h, w*A['n'])
            for i in range(A['n']):
                tile = pixels[:,i*w:(i+1)*w]
                assert tile[:,:,3].max() > 0, (rel, i, 'empty')
                hashes.append(hashlib.sha256(tile.tobytes()).hexdigest())
                if tile[:,:,3].max() <= 240:
                    assert reference[:,i*w:(i+1)*w,3].max() <= 240
                    translucent.append(i)
            assert len(set(hashes)) == A['n'], (rel, 'duplicates')
            result.update(cell=[w,h], frames=A['n'], rows=1, nonempty_unique=True, original_translucent_cells=translucent)
            assert not dest.with_name(dest.stem+'_n.png').exists()
            e = dest.with_name(dest.stem+'_e.png')
            original_e = cel.ARCHIVE/rel.replace('.png','_e.png')
            assert digest(e) == digest(original_e)
            result.update(size=Image.open(dest).size, accent_iou=1.0, emission_unchanged=True, normals_absent=True)
            checks.append(result)
            row.append((rel, (w,h), min(2,A['n']-1), 0))
        samples.append(row[:4])
    after = {str(p.relative_to(sprites)): digest(p) for p in sprites.rglob('*') if p.is_file()}
    assert before.keys() == after.keys()
    assert all(before[k] == after[k] for k in before if k not in rewritten), 'untargeted file changed'
    decisions = {}
    for folder in sorted(p for p in sprites.iterdir() if p.is_dir()):
        name = folder.name
        reason = ('disque opaque et fumée; prop' if name == 'meteor' else 'fumée; vfx') if name in TARGETS else {
            'chest_open': 'halo/rayons/étoiles uniquement; aucun coffre dans make_chest',
            'phoenix': 'plumes en flame émissives; aucune plume solide',
            'ardent_brasier': 'lot R1', 'ardent_nova': 'lot R1',
            'source': 'pluie lumineuse; ambiance protégée',
        }.get(name, 'lumière/particules; exclusion explicite')
        decisions[name] = {'action': 're-rendu' if name in TARGETS else 'laissé', 'raison': reason}
    report = dict(checks=checks, dossiers=decisions, profiles=TARGETS,
                  bytes_before=bytes_before, bytes_after=sum(p.stat().st_size for p in sprites.rglob('*.png')),
                  resources_and_untargeted_unchanged=True,
                  choices='Billboards originaux; alpha procédural conservé; rampes du module partagé. Masques _e originaux conservés exactement. Aucun coffre ni plume solide inventé.')
    REPORT.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding='utf-8')
    cel.contact_pair(samples, HERE/'_cel_vfx_contact.png', size=(1440,900))
    print('PASS CEL VFX', len(checks), 'sheets')

if __name__ == '__main__':
    render() if '--render' in sys.argv else driver()
